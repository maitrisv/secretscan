#!/usr/bin/env python3
"""Write FAKE provider-format credentials into a directory for secretscan to find.

The tokens are assembled at runtime from fragments, so this file never contains a
complete credential-shaped string. That keeps GitHub push protection (and other
secret scanners) from rejecting the repository, while the files this script
*writes* still exercise the scanner's detection rules.

Usage:
    python3 examples/make_secret_fixtures.py DEST_DIR
"""
from __future__ import annotations

import sys
from pathlib import Path


def build_fixtures() -> dict[str, str]:
    j = "".join
    aws_id = j(["AKIA", "IOSFODNN7EXAMPLE"])
    aws_secret = j(["wJalrXUtnFEMI/K7MDENG/", "bPxRfiCYEXAMPLEKEY"])
    google = j(["AIza", "SyA1b2C3d4E5f6G7h8I9j0K1l2M3n4O5p6Q"])
    slack = j(["xox", "b-123456789012-abcdefghijklmnopqrstuvwx"])
    stripe = j(["sk_", "live_Zq8Lm2Xv9Tn4Rb7Wc1Hd5Jf3"])
    github = j(["gh", "p_abcdefghijklmnopqrstuvwxyz0123456789"])
    pem_head = j(["-----BEGIN OPENSSH PRIVATE", " KEY-----"])
    pem_foot = j(["-----END OPENSSH PRIVATE", " KEY-----"])

    return {
        "config.py": (
            '"""FAKE credentials generated by make_secret_fixtures.py."""\n'
            f'AWS_ACCESS_KEY_ID = "{aws_id}"\n'
            f'AWS_SECRET_ACCESS_KEY = "{aws_secret}"\n'
            f'GOOGLE_MAPS_KEY = "{google}"\n'
            f'KNOWN_TEST_KEY = "{aws_id}"  # secretscan:ignore\n'
        ),
        "deploy.sh": (
            "#!/bin/sh\n"
            "# FAKE credentials: exercises the regex pass on non-Python files.\n"
            f'export SLACK_TOKEN="{slack}"\n'
            f'export STRIPE_KEY="{stripe}"\n'
            f'curl -H "Authorization: Bearer {github}" https://api.example.com/deploy\n'
        ),
        "id_rsa_demo": f"{pem_head}\nZmFrZS1rZXktZm9yLWRlbW8tcHVycG9zZXMtb25seQ==\n{pem_foot}\n",
    }


def write_fixtures(dest: Path) -> list[Path]:
    dest.mkdir(parents=True, exist_ok=True)
    written = []
    for name, content in build_fixtures().items():
        path = dest / name
        path.write_text(content, encoding="utf-8")
        written.append(path)
    return written


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: make_secret_fixtures.py DEST_DIR")
    for p in write_fixtures(Path(sys.argv[1])):
        print(f"wrote {p}")
